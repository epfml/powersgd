#!/usr/bin/env python3
"""Rebuild results/budget.md from Slurm accounting (sacct). Run on a Perlmutter login node.

Reads results/budget_config.json:
  {"accounts": {"m4431_g": {"allocation_node_hours": null}},   # fill in from Iris
   "since": "2026-10-29",
   "planned": [{"name": "tier1 resnet18 1-node", "account": "m4431_g", "node_hours": null}]}
Node-hours = NNodes x Elapsed hours per job (the allocation is charged per node, not per GPU).
Use --sacct-file to feed saved `sacct -P -n -X --format=JobID,JobName,Account,Elapsed,NNodes,State` output (testing).
"""
import argparse
import json
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FMT = "JobID,JobName,Account,Elapsed,NNodes,State"


def elapsed_h(s):
    days, _, hms = s.rpartition("-")
    h, m, sec = (float(x) for x in hms.split(":"))
    return (float(days) * 24 if days else 0) + h + m / 60 + sec / 3600


def get_jobs(cfg, sacct_file):
    if sacct_file:
        text = Path(sacct_file).read_text()
    else:
        accts = ",".join(cfg["accounts"])
        text = subprocess.check_output(["sacct", "-u", subprocess.check_output(["whoami"], text=True).strip(), "-A", accts,
                                        "-S", cfg.get("since", "2026-10-29"), "-X", "-n", "-P", "--format", FMT], text=True)
    jobs = []
    for line in text.splitlines():
        if not line.strip():
            continue
        jid, name, acct, el, nn, state = line.split("|")[:6]
        jobs.append({"job": jid, "name": name, "account": acct, "elapsed": el, "nodes": int(nn), "state": state,
                     "node_hours": int(nn) * elapsed_h(el)})
    return jobs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sacct-file")
    ap.add_argument("--config", default=str(ROOT / "results" / "budget_config.json"))
    ap.add_argument("--out", default=str(ROOT / "results" / "budget.md"))
    a = ap.parse_args()
    cfg = json.loads(Path(a.config).read_text())
    jobs = get_jobs(cfg, a.sacct_file)
    used, planned = defaultdict(float), defaultdict(float)
    for j in jobs:
        used[j["account"]] += j["node_hours"]
    for p in cfg.get("planned", []):
        planned[p["account"]] += p["node_hours"] or 0
    f = lambda x: "unknown" if x is None else f"{x:.2f}"
    out = ["# Budget (auto-generated by tools/update_budget.py; 1 node = 4 GPUs, GPU-hours = 4 x node-hours)\n",
           "| Account | Allocation (node-h) | Used (node-h) | Used (GPU-h) | Remaining (node-h) | Planned, not yet run (node-h) | Remaining after plan |",
           "|---|---|---|---|---|---|---|"]
    for acct, c in cfg["accounts"].items():
        alloc = c.get("allocation_node_hours")
        rem = None if alloc is None else alloc - used[acct]
        after = None if rem is None else rem - planned[acct]
        out.append(f"| {acct} | {f(alloc)} | {used[acct]:.2f} | {4 * used[acct]:.2f} | {f(rem)} | {planned[acct]:.2f} | {f(after)} |")
    out += ["", "## Jobs (from sacct)", "| JobID | Name | Account | Elapsed | Nodes | State | Node-hours |", "|---|---|---|---|---|---|---|"]
    out += [f"| {j['job']} | {j['name']} | {j['account']} | {j['elapsed']} | {j['nodes']} | {j['state']} | {j['node_hours']:.3f} |" for j in jobs]
    out += ["", "## Planned runs (estimates, not yet run)", "| Name | Account | Node-hours |", "|---|---|---|"]
    out += [f"| {p['name']} | {p['account']} | {f(p['node_hours'])} |" for p in cfg.get("planned", [])]
    Path(a.out).write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
